export function resolveLanguage(requested, stored) {
  const supported = (value) => value === "ko" || value === "en";
  return supported(requested) ? requested : supported(stored) ? stored : DEFAULT_LANGUAGE;
}

export function message(language, key, values = {}) {
  const template = MESSAGES[language]?.[key] ?? MESSAGES[DEFAULT_LANGUAGE][key];
  if (typeof template !== "string") throw new Error(`Unknown translation key: ${key}`);
  return template.replace(/\{(\w+)\}/g, (token, name) => String(values[name] ?? token));
}

export function cleanText(text = "") {
  return text.replace(/^\uFEFF/, "").replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, "").trim();
}

export function localizeRelease(release, translations, language) {
  const originalName = cleanText(release.name || "") || `MASKLESS LITHO ${release.tag_name}`;
  const originalBody = cleanText(release.body || "");
  if (language === "ko") return { ...release, name: originalName, body: originalBody };

  const translated = translations[release.tag_name];
  const hasKorean = (text) => /[\u1100-\u11FF\u3130-\u318F\uAC00-\uD7AF]/.test(text || "");
  const englishText = (text) => typeof text === "string" && !hasKorean(text) ? cleanText(text) : "";
  return {
    ...release,
    name: englishText(translated?.name) || englishText(originalName) || `MASKLESS LITHO ${release.tag_name}`,
    body: englishText(translated?.body) || (hasKorean(originalBody)
      ? message("en", "missingEnglishNotes")
      : originalBody),
  };
}
